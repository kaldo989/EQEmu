-- Mercenary AA ability types, and the db_str category 36 label swap
-- ---------------------------------------------------------------------------
-- MANUAL IMPORT. Nothing in the server creates or applies these rows.
--
-- What this fixes
-- ---------------
-- Opcode 0x78e8 (OP_MercenaryAAAbilities) carries ten u32 fields per ability. Two of them
-- are now proven from the client rather than guessed:
--
--   FUN_14033cd80 builds each row of AAW_MercAAList from the parsed record (call it f[]):
--     column 0  CDBStr__GetString(f[1], 0x25)   -> category 37, ability name
--     column 1  "%d/%d" from f[5] and GetMercMaxRank
--     column 2  DAT_14081c65c formatted with f[3]                -> cost
--     column 3  f[6] > 0 ? CDBStr__GetString(f[6], 0x24) : ""    -> category 36, ability type
--
--   FUN_1401a53f0 is the buy gate on the same record:
--     (int)f[3] <= *(int *)(pinstLocalPC + 0x2738)   -> cost against the AA point pool
--     (int)f[7] <= <player level>                    -> level requirement
--     FUN_1401251e0(mgr + 0x488, f[8])               -> alternate currency id
--
-- So f3 is the cost and f6 is the ability type. The server was sending max_rank in f3 and
-- zero in f6, which is why the Merc page of the AA window has an empty Type column and an
-- empty AAW_MercTypeFilter, and why the cost column showed the rank count.
--
-- f6 is looked up in dbstr category 36. That category has exactly five members in the
-- client (dbstr_us.txt lines 30, 69, 108, 147, 181):
--
--   1^36^General^0^
--   2^36^Tank^0^
--   3^36^Healer^0^
--   4^36^Melee DPS^0^
--   5^36^Caster DPS^0^
--
-- CDBStr__GetString does not return null when a lookup misses. It formats
-- "Unknown DB String %d-%d" and hands that back as the label, so any f6 outside 1..5 shows
-- up verbatim inside the AA list row. Zero is the only safe value, and it renders a blank
-- cell because the client guards the call with `0 < f6`.
--
-- Where the aa_type values below come from
-- ----------------------------------------
-- They are not guesses. The client's own rank-1 descriptions (dbstr category 38) name the
-- mercenary type each ability belongs to:
--
--   101 "increases your mercenary's maximum health"                      -> General
--   201 "increases your mercenary's maximum mana"                        -> General
--   301 "increases your mercenary's base armor class"                    -> General
--   401 "improves your mercenary's ... resistances"                      -> General
--  1000 "hate generated by your tank mercenary's attacks"                -> Tank
--  1001 "hate generated by your tank mercenary's attacks"                -> Tank
--  1100 "reduces incoming melee damage for your tank mercenary"          -> Tank
--  1200 "hate generated by your healer mercenary's spells"               -> Healer
--  1300 "your healer mercenary's instant-duration healing spells"        -> Healer
--  1400 "hate generated by your melee damage mercenary's attacks"        -> Melee DPS
--  1500 "the damage your melee damage mercenary deals"                   -> Melee DPS
--  1600 "hate generated by your damage caster mercenary's spells"        -> Caster DPS
--  1700 "the damage dealt by your damage caster mercenary's spells"      -> Caster DPS
--  5000 "grants your mercenary immunity to Gust of Atrebe"               -> General
--
-- "melee damage mercenary" is category 36 id 4 in the client, and "damage caster
-- mercenary" is id 5.
--
-- The second half of this file fixes the server's copy of category 36, where ids 4 and 5
-- are reversed. db_str is the server's own copy of dbstr_us.txt and is what
-- Zone::ValidateMercenaryStrings() audits against, so a reversed pair makes the audit
-- disagree with the client. The client always renders its own file, so this half is about
-- keeping the server's copy faithful.
--
-- Safe to re-run: every statement is an UPDATE keyed on the primary key.
-- ---------------------------------------------------------------------------

-- Preflight: what the tables look like before the import.
SELECT ability_id, name_sid, max_rank, group_id, rank_index, aa_type, cost
	FROM merc_aa_ability ORDER BY ability_id;

SELECT id, value FROM db_str WHERE type = 36 ORDER BY id;

-- 1. Ability types (dbstr category 36).
UPDATE `merc_aa_ability` SET `aa_type` = 1 WHERE `ability_id` IN (101, 201, 301, 401, 5000);
UPDATE `merc_aa_ability` SET `aa_type` = 2 WHERE `ability_id` IN (1000, 1001, 1100);
UPDATE `merc_aa_ability` SET `aa_type` = 3 WHERE `ability_id` IN (1200, 1300);
UPDATE `merc_aa_ability` SET `aa_type` = 4 WHERE `ability_id` IN (1400, 1500);
UPDATE `merc_aa_ability` SET `aa_type` = 5 WHERE `ability_id` IN (1600, 1700);

-- 2. Category 36 labels, matched to the client's dbstr_us.txt.
UPDATE `db_str` SET `value` = 'Melee DPS'  WHERE `type` = 36 AND `id` = 4;
UPDATE `db_str` SET `value` = 'Caster DPS' WHERE `type` = 36 AND `id` = 5;

-- Postcheck: aa_type must be 1..5, and category 36 must read General, Tank, Healer,
-- Melee DPS, Caster DPS in id order.
SELECT ability_id, name_sid, aa_type,
	CASE WHEN aa_type BETWEEN 1 AND 5 THEN 'ok' ELSE 'INVALID' END AS aa_type_check
	FROM merc_aa_ability ORDER BY ability_id;

SELECT id, value FROM db_str WHERE type = 36 ORDER BY id;

SELECT a.ability_id, a.aa_type, IFNULL(s.value, 'MISSING FROM db_str CATEGORY 36') AS type_label
	FROM merc_aa_ability a
	LEFT JOIN db_str s ON s.id = a.aa_type AND s.type = 36
	WHERE a.aa_type <> 0
	ORDER BY a.ability_id;
